"""Generates PROJECT_STATUS.md from a single source of truth.

The specification (section 10) requires the coding agent to own this file. Keeping
it generated means the summary table, the phase checklist and the per-phase detail
can never drift apart.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUS_PATH = ROOT / "PROJECT_STATUS.md"
PHASES_PATH = ROOT / "config" / "project_phases.json"

TICK = {"pass": "✅ **PASS**", "in_progress": "⏳ IN PROGRESS",
        "not_started": "⬜ NOT STARTED", "blocked": "🛑 BLOCKED"}
BOX = {"pass": "[x]", "in_progress": "[ ]", "not_started": "[ ]", "blocked": "[ ]"}


def load_phases() -> dict:
    return json.loads(PHASES_PATH.read_text(encoding="utf-8"))


def render(doc: dict) -> str:
    phases = doc["phases"]
    total_passed = sum(p.get("tests", {}).get("passed", 0) for p in phases)
    total_failed = sum(p.get("tests", {}).get("failed", 0) for p in phases)
    total_skipped = sum(p.get("tests", {}).get("skipped", 0) for p in phases)

    current = next((p for p in phases if p["status"] == "in_progress"), None)
    current_name = "Phase {} — {}".format(current["number"], current["name"]) if current \
        else "Complete"

    L = [
        "# Excel_sense_v2 - Project Status",
        "",
        "Last updated: {}".format(doc["last_updated"]),
        "Current phase: **{}**".format(current_name),
        "Overall status: **{}**".format(doc["overall_status"]),
        "",
        "Generated by `scripts/status.py` from `config/project_phases.json`, "
        "per specification §10. Do not edit by hand.",
        "",
        "---",
        "",
        "## 0. Phase Checklist",
        "",
    ]
    for p in phases:
        L.append("- {} Phase {} — {}".format(BOX[p["status"]], p["number"], p["name"]))

    L += ["", "---", "", "## 1. Phase Summary — Expected vs Done vs Tests", "",
          "| # | Phase | Expected deliverables (spec) | Delivered | Tests | Gate |",
          "|---|---|---|---|---|---|"]
    for p in phases:
        tests = p.get("tests")
        if tests and tests.get("passed"):
            cell = "**{} passed / {} failed**".format(tests["passed"], tests.get("failed", 0))
        else:
            cell = "—"
        L.append("| {} | {} | {} | {} | {} | {} |".format(
            p["number"], p["name"], p["expected"], p["delivered"], cell, TICK[p["status"]]))

    L += ["", "**Cumulative tests: {} passed, {} failed, {} skipped.**".format(
        total_passed, total_failed, total_skipped), "", "---", ""]

    section = 2
    for p in phases:
        if p["status"] == "not_started":
            continue
        L += render_phase(p, section)
        section += 1

    L += ["# {}. Feature Checklist".format(section), ""]
    for group, items in doc["features"].items():
        L += ["## {}".format(group), ""]
        for item, done in items:
            L.append("- [{}] {}".format("x" if done else " ", item))
        L.append("")
    return "\n".join(L)


def render_phase(p: dict, section: int) -> list:
    heading = "## {}. Phase {} — {} — {}".format(
        section, p["number"], p["name"],
        {"pass": "✅ COMPLETE", "in_progress": "⏳ IN PROGRESS",
         "blocked": "🛑 BLOCKED"}[p["status"]])
    L = [heading, ""]
    if p.get("gate"):
        verdict = {"pass": "→ **PASSED**", "in_progress": "→ not yet evaluated",
                   "blocked": "→ **BLOCKED**"}[p["status"]]
        L += ["**Gate:** *{}* {}".format(p["gate"], verdict), ""]

    if p.get("tasks"):
        L += ["### {}.1 Expected vs Done".format(section), "",
              "| Spec task | Expected | Done | Evidence |", "|---|---|---|---|"]
        for task in p["tasks"]:
            L.append("| {} | yes | {} | {} |".format(
                task["task"], "✅" if task["done"] else "⏳", task.get("evidence", "")))
        L.append("")

    if p.get("deliverables"):
        L += ["### {}.2 Deliverables".format(section), "",
              "| Deliverable | Path | Status |", "|---|---|---|"]
        for d in p["deliverables"]:
            L.append("| {} | `{}` | {} |".format(
                d["what"], d["path"], "✅ " + d.get("note", "") if d["present"] else "⏳"))
        L.append("")

    if p.get("test_matrix"):
        L += ["### {}.3 Test status".format(section), "",
              "| Spec-required test | Result |", "|---|---|"]
        for t in p["test_matrix"]:
            L.append("| {} | {} |".format(t["test"], t["result"]))
        L.append("")

    tests = p.get("tests")
    if tests:
        L += ["**{} passed, {} failed, {} skipped** for this phase.".format(
            tests.get("passed", 0), tests.get("failed", 0), tests.get("skipped", 0)), ""]

    for block in p.get("sections", []):
        L += ["### {}.{} {}".format(section, block["index"], block["title"]), "",
              block["body"], ""]

    if p.get("limitations"):
        L += ["### Known limitations", ""]
        L += ["- {}".format(x) for x in p["limitations"]]
        L.append("")

    if p.get("blockers"):
        L += ["### Blocked", ""]
        L += ["- {}".format(x) for x in p["blockers"]]
        L.append("")
    elif p["status"] == "in_progress":
        L += ["### Blocked", "", "- None.", ""]

    if p.get("next_action"):
        L += ["### Next Action", "", p["next_action"], ""]

    L += ["---", ""]
    return L


def main() -> None:
    doc = load_phases()
    STATUS_PATH.write_text(render(doc), encoding="utf-8")
    print("wrote {} ({:,} bytes)".format(STATUS_PATH.name, STATUS_PATH.stat().st_size))


if __name__ == "__main__":
    main()
